import numpy as np
import json
import os
from scipy.interpolate import interp1d

def weighted_dlt_triangulate(projection_matrices, points_2d, confidences):
    """
    Calculates the 3D coordinate using a Weighted N-Camera DLT.
    
    Arguments:
    - projection_matrices: List of 3x4 numpy arrays (the P matrices for each valid camera).
    - points_2d: List of [u, v] pixel coordinates corresponding to each valid camera.
    - confidences: List of YOLO confidence scores (used to weight the math).
    
    Returns:
    - A numpy array [X, Y, Z] representing the 3D spatial coordinate.
    """
    A = []
    
    for P, (u, v), weight in zip(projection_matrices, points_2d, confidences):
        # High confidence = strong pull on the 3D point. Low confidence = weak pull.
        row1 = weight * (u * P[2, :] - P[0, :])
        row2 = weight * (v * P[2, :] - P[1, :])
        
        A.append(row1)
        A.append(row2)
        
    A = np.array(A)
    
    # Singular Value Decomposition solves the matrix for the intersection point
    _, _, Vh = np.linalg.svd(A)
    X = Vh[-1, :]
    
    return X[:3] / X[3]


