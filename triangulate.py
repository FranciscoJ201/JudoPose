def dlt_triangulate(projection_matrices, points_2d):
    """
    Calculates the 3D coordinate of a single joint using N-Camera Direct Linear Transformation.
    
    Arguments:
    - projection_matrices: A list of 3x4 numpy arrays (the P matrices for each valid camera).
    - points_2d: A list of [u, v] pixel coordinates corresponding to each valid camera.
    
    Returns:
    - A numpy array [X, Y, Z] representing the 3D spatial coordinate.
    """
    A = []
    
    # We construct the DLT matrix equation A*X = 0 by stacking the equations for each camera
    for P, (u, v) in zip(projection_matrices, points_2d):
        A.append(u * P[2, :] - P[0, :])
        A.append(v * P[2, :] - P[1, :])
        
    A = np.array(A)
    
    # Singular Value Decomposition (SVD) mathematically finds the point with the shortest 
    # distance to all intersecting 3D rays simultaneously.
    _, _, Vh = np.linalg.svd(A)
    X = Vh[-1, :]
    
    # Convert from homogeneous coordinates (X, Y, Z, W) back to standard 3D (X, Y, Z)
    return X[:3] / X[3]


