def interpolate_missing_data(trajectory_3d):
    """
    Fills in missing 3D coordinates (NaNs) across a timeline using cubic spline interpolation.
    
    Arguments:
    - trajectory_3d: A numpy array of shape (num_frames, 3) representing the X, Y, Z timeline of a single joint.
    
    Returns:
    - A smoothed numpy array (num_frames, 3) with missing frames mathematically guessed.
    """
    frames = np.arange(len(trajectory_3d))
    valid_mask = ~np.isnan(trajectory_3d[:, 0])
    
    # If the joint was completely blocked for the entire video, return as-is
    if not np.any(valid_mask):
        return trajectory_3d
        
    smoothed_trajectory = np.empty_like(trajectory_3d)
    
    # Interpolate each axis (X, Y, and Z) independently across the timeline
    for axis in range(3):
        valid_frames = frames[valid_mask]
        valid_data = trajectory_3d[valid_mask, axis]
        
        # Create the interpolation mathematical model based on the visible frames
        interpolator = interp1d(valid_frames, valid_data, kind='cubic', fill_value="extrapolate")
        
        # Apply the model to fill in the missing frames
        smoothed_trajectory[:, axis] = interpolator(frames)
        
    return smoothed_trajectory


